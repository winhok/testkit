import assert from 'node:assert/strict';
import { analyzeSource } from '../scripts/analyze_ast.mjs';

const result = analyzeSource(`
import admin from './admin.js';
const base = '/reports';
const routes = [{path:base, children:[{path:':id'}, {index:true}]}];
createBrowserRouter(routes);
fetch('/api/reports', {method:'POST'});
axios.get('/api/profile');
import('./detail.js');
localStorage.setItem('filter', 'SECRET');
`);
assert.deepEqual(result.routes.map(row=>row.path), ['/reports','/reports/:id','/reports']);
assert.deepEqual(result.requests.map(row=>row.method), ['POST','GET']);
assert.deepEqual(result.imports.map(row=>row.value), ['./admin.js','./detail.js']);
assert.ok(result.routes.every(row=>row.line > 0 && row.column >= 0));
assert.ok(!JSON.stringify(result).includes('SECRET'));
assert.equal(analyzeSource('// createBrowserRouter([{path:"/fake"}])').routes.length,0);
assert.equal(analyzeSource('const other={path:"/not-a-route"};').routes.length,0);
assert.deepEqual(analyzeSource('const r=[{path:"/a",children:[{path:"b"}]}]; createRouter({routes:r})').routes.map(row=>row.path),['/a','/a/b']);
assert.deepEqual(analyzeSource('const x=<Route path="/a"><Route path=":id" /></Route>').routes.map(row=>row.path),['/a','/a/:id']);
assert.equal(analyzeSource('let p="/a"; createBrowserRouter([{path:p}]);').routes.length,0);
assert.equal(analyzeSource('const p="/a"; function f(p){navigate(p)}').routes.length,0);
assert.equal(analyzeSource('const r=[{path:"/a"}]; r.push({path:"/b"}); createBrowserRouter(r)').routes.length,0);
assert.equal(analyzeSource('const r=[{path:"/old"}];const a=r;a.push({path:"/new"});createBrowserRouter(r)').routes.length,0);
assert.equal(analyzeSource('const r=[{...other,path:"/a"}]; createBrowserRouter(r)').routes.length,0);
assert.equal(analyzeSource('const r=[{path: compute()}];createBrowserRouter(r)').unknowns[0].reason,'computed-route-path');
assert.equal(analyzeSource('const x = ').unknowns[0].reason,'parse-failed');
assert.equal(analyzeSource('fetch("/api/x",opts)').requests[0].method,null);
assert.equal(analyzeSource('fetch("/api/x")').requests[0].method,'GET');
assert.equal(analyzeSource('const base="/api";fetch(`${base}/items`)').requests[0].value,'/api/items');
assert.equal(analyzeSource('const routes = [] as const;createBrowserRouter(routes)').unknowns.length,0);
assert.equal(analyzeSource('globalThis.__testkitExecuted=true').requests.length,0);
assert.equal(globalThis.__testkitExecuted,undefined);
assert.equal(analyzeSource('createBrowserRouter([{path:"/reports"}],{basename:"/console"})').routes[0].path,'/console/reports');
assert.equal(analyzeSource('createRouter({routes:[{path:"/reports"}],history:createWebHistory("/console")})').routes[0].path,'/console/reports');
assert.equal(analyzeSource('createBrowserRouter([{path:"/reports"}],{basename: dynamic()})').unknowns[0].reason,'unresolved-router-base');
console.log('AST route, request, module, inertness and unknown-boundary checks passed');
